"""Prompts. The planner writes ingestion code; the worker writes explanations and the narrative.
Numbers in worker output must come from the facts we pass in (the verifier enforces this)."""

from __future__ import annotations

import json

CANONICAL_SPEC = """Return a pandas DataFrame with one row per measurement and these columns:
- channel_id (str): tester channel / cell identifier
- cycle (int, starting at 1): one charge followed by one discharge
- step (int): consecutive segment number within the channel (charge, rest, discharge ...)
- time_s (float): seconds, non-decreasing within each channel
- voltage_v (float): volts
- current_a (float): amps, POSITIVE WHILE CHARGING, negative while discharging
Optional: temperature_c (float, degC), capacity_ah (float, Ah)."""

HELPERS_DOC = """You may `import vera_helpers` (it is importable) for generic conversions:
- vera_helpers.hhmmss_to_seconds(values) -> Series      # 'hh:mm:ss' or 'd.hh:mm:ss' strings to seconds
- vera_helpers.matlab_datenum_to_seconds(values) -> ndarray   # MATLAB datenum days to seconds since first sample
- vera_helpers.steps_from_current(current) -> ndarray   # segment numbers from current sign changes
- vera_helpers.cycles_from_current(current) -> ndarray  # cycle index from charge/discharge pattern (positive = charge)"""

PLANNER_SYSTEM = (
    "You are Vera's ingestion engineer. Battery formation and grading testers export data in many layouts. "
    "You write one robust, readable Python function that converts an unfamiliar export into Vera's canonical table. "
    "Infer the layout only from the structural summary you are given. Allowed imports: pandas, numpy, scipy, openpyxl, "
    "h5py, re, math, vera_helpers. No network access, no file writes, no prints of the data. "
    "Reply with exactly one ```python code block and nothing else."
)


def normalizer_prompt(filename: str, peek_text: str) -> str:
    return f"""Write `def normalize(path: str) -> pandas.DataFrame` for the file `{filename}`.

{CANONICAL_SPEC}

{HELPERS_DOC}

Rules:
- Convert units (mV -> V, mA -> A, mAh -> Ah, minutes or hours -> seconds). Watch for decimal commas and preamble lines.
- Fix the current sign if the file uses discharge-positive.
- One file may hold many channels (rows, columns, sheets or struct fields). Return all of them in long format.
- If cycle or step labels are missing, derive them with the helpers. If a time axis restarts per step, rebuild a
  cumulative time per channel.
- Keep it fast: vectorised pandas, no per-row Python loops over hundreds of thousands of rows.
- Keep the result under about 3 million rows. If the file holds more samples, keep every k-th sample inside each
  step, always keeping each step's first and last sample (capacity is integrated over time, so this is safe).
- The path may be a zip archive: open it with zipfile and read the data members (skip README files).

Structural summary of the file (generated by code, values truncated):
{peek_text}
"""


def repair_prompt(code: str, problem: str) -> str:
    return f"""Your normalize() did not produce an acceptable canonical table.

Problem:
{problem}

Your previous code:
```python
{code}
```

Fix the cause (do not just suppress the error) and return the complete corrected module in one ```python block."""


WORKER_SYSTEM = (
    "You are Vera, a battery quality-control assistant writing for process and quality engineers. "
    "Be concrete and brief. Use only numbers that appear in the facts you are given, copied with the same digits; "
    "never compute new numbers and never invent any."
)

FAULT_WORDS = {
    "LOW_CAPACITY": "low capacity",
    "HIGH_IR": "high internal resistance",
    "CURVE_SHAPE": "an unusual voltage-curve shape",
    "CAPACITY_CREEP_UP": "capacity creeping up across cycles",
    "LOW_CE": "low first-cycle coulombic efficiency",
    "NOISY_OR_DEAD_CHANNEL": "a noisy or dead channel",
}


def explain_prompt(fault: str, rows: list[dict]) -> str:
    return f"""Flag type: {fault} ({FAULT_WORDS.get(fault, fault)}).
Flagged channels with the evidence computed by code (JSON):
{json.dumps(rows, indent=1)}

For each channel write one sentence (max 30 words) that a quality engineer can act on: what was measured, how it
compares with the batch median, and the likely practical meaning. Reply with JSON only:
{{"explanations": {{"<channel_id>": "<sentence>", ...}}}}"""


def narrative_prompt(facts: dict) -> str:
    return f"""Facts about one batch, computed by code (JSON):
{json.dumps(facts, indent=1)}

Write the summary paragraph of the QC report: 4 to 6 sentences, plain language, for a process engineer deciding
what to do with this batch. Mention how many channels were graded, the grade split, which fault types appeared and
the most important channels to look at. Use only the numbers in the facts, copied exactly. No headings, no lists."""


def fix_sentence_prompt(sentence: str, bad: list[str], facts: dict) -> str:
    return f"""This sentence contains numbers that do not match the facts: {bad}

Sentence: {sentence}

Facts (JSON): {json.dumps(facts)}

Rewrite the sentence using only numbers present in the facts, or remove the numbers. Reply with the sentence only."""
