// Prompts for the Forge edition. The planner describes a layout (JSON); it never writes code here.
import type { Mapping } from "./reader.ts";

export const PLANNER_SYSTEM =
  "You are Vera's ingestion engineer. Battery formation and grading testers export data in many layouts. " +
  "From a structural summary of one export, you describe its layout as a JSON mapping that a deterministic reader applies. " +
  "Reply with one JSON object and nothing else.";

export const MAPPING_SPEC = `Mapping fields:
- delimiter: the field separator, e.g. "," ";" "\\t" "|"
- decimal: "." or "," (decimal comma, e.g. 3412,5)
- header_row: 0-based index of the line that holds the column names (skip any preamble lines before it)
- orientation: "long" (one row per measurement, channel in a column) or "wide" (one row per time step, columns per channel)
- columns (long only): [{"source": "<exact header text>", "role": <role>, "scale": <multiplier to SI units>}]
    roles: "channel_id", "cycle", "step", "time", "voltage_v", "current_a", "temperature_c", "capacity_ah", "ignore"
    scale examples: mV -> 0.001, mA -> 0.001, mAh -> 0.001, V or A -> 1; for "time" use 1 and set time_format
- time_column (wide only): exact header text of the shared time column
- voltage_pattern, current_pattern (wide only): regex with ONE capture group for the channel id, e.g. "^(.+)_V$"
- voltage_scale, current_scale (wide only): multipliers to V and A
- time_format: "seconds", "minutes", "hours", "days", "hh:mm:ss" or "timestamp"
- current_sign: "charge_positive" if charging current is positive in the file, else "discharge_positive"
- single_channel_id: a name for the cell if the file holds one cell and has no channel column, else null
- confidence: 0 to 1
- notes: one short sentence about anything unusual
Omit cycle and step columns if the file has none; the reader derives them from the current.`;

export function mappingPrompt(filename: string, peek: string): string {
  return `Describe the layout of \`${filename}\` as a JSON mapping.

${MAPPING_SPEC}

Structural summary of the file (generated by code, values truncated):
${peek}`;
}

export function repairPrompt(previous: unknown, problem: string): string {
  return `Your mapping did not produce an acceptable table.

Problem:
${problem}

Previous mapping:
${JSON.stringify(previous, null, 1)}

Fix the cause and reply with the complete corrected JSON mapping only.`;
}

const ROLES = new Set(["channel_id", "cycle", "step", "time", "voltage_v", "current_a", "temperature_c", "capacity_ah", "ignore"]);
const TIME_FORMATS = new Set(["seconds", "minutes", "hours", "days", "hh:mm:ss", "timestamp"]);

/** Shape check of the model's JSON; throws a message that is fed back for repair. */
export function parseMapping(obj: unknown): Mapping {
  const m = obj as Record<string, any>;
  const errs: string[] = [];
  if (!m || typeof m !== "object") throw new Error("mapping must be a JSON object");
  if (typeof m.delimiter !== "string" || !m.delimiter) errs.push("delimiter must be a non-empty string");
  if (m.decimal !== "." && m.decimal !== ",") errs.push('decimal must be "." or ","');
  if (!Number.isInteger(m.header_row) || m.header_row < 0) errs.push("header_row must be a non-negative integer");
  if (m.orientation !== "long" && m.orientation !== "wide") errs.push('orientation must be "long" or "wide"');
  if (!TIME_FORMATS.has(m.time_format)) errs.push(`time_format must be one of ${[...TIME_FORMATS].join(", ")}`);
  if (m.current_sign !== "charge_positive" && m.current_sign !== "discharge_positive") errs.push('current_sign must be "charge_positive" or "discharge_positive"');
  if (m.orientation === "long") {
    if (!Array.isArray(m.columns) || !m.columns.length) errs.push("long mapping needs a non-empty columns array");
    else for (const c of m.columns) if (typeof c?.source !== "string" || !ROLES.has(c?.role)) errs.push(`bad column entry ${JSON.stringify(c)}`);
  }
  if (m.orientation === "wide") {
    for (const k of ["time_column", "voltage_pattern", "current_pattern"]) if (typeof m[k] !== "string" || !m[k]) errs.push(`wide mapping needs ${k}`);
    for (const k of ["voltage_pattern", "current_pattern"]) { try { if (m[k]) new RegExp(m[k]); } catch { errs.push(`${k} is not a valid regex`); } }
  }
  if (errs.length) throw new Error(`mapping shape errors: ${errs.join("; ")}`);
  if (m.delimiter === "\\t") m.delimiter = "\t";
  return m as Mapping;
}

export const WORKER_SYSTEM =
  "You are Vera, a battery quality-control assistant writing for process and quality engineers. Be concrete and brief. " +
  "Use only numbers that appear in the facts you are given, copied with the same digits; never compute new numbers and never invent any.";

const FAULT_WORDS: Record<string, string> = {
  LOW_CAPACITY: "low capacity", HIGH_IR: "high internal resistance", CURVE_SHAPE: "an unusual voltage-curve shape",
  CAPACITY_CREEP_UP: "capacity creeping up across cycles", LOW_CE: "low first-cycle coulombic efficiency",
  NOISY_OR_DEAD_CHANNEL: "a noisy or dead channel",
};

export function explainPrompt(fault: string, rows: unknown[]): string {
  return `Flag type: ${fault} (${FAULT_WORDS[fault] ?? fault}).
Flagged channels with the evidence computed by code (JSON):
${JSON.stringify(rows, null, 1)}

For each channel write one sentence (max 30 words) that a quality engineer can act on: what was measured, how it
compares with the batch median, and the likely practical meaning. Reply with JSON only:
{"explanations": {"<channel_id>": "<sentence>", ...}}`;
}

export function narrativePrompt(facts: unknown): string {
  return `Facts about one batch, computed by code (JSON):
${JSON.stringify(facts, null, 1)}

Write the summary of the QC report: 4 to 6 sentences, plain language, for a process engineer deciding what to do with
this batch. Mention how many channels were graded, the grade split, which fault types appeared and the most important
channels to look at. Use only the numbers in the facts, copied exactly. No headings, no lists.`;
}

export function fixSentencePrompt(sentence: string, bad: string[], facts: unknown): string {
  return `This sentence contains numbers that do not match the facts: ${JSON.stringify(bad)}

Sentence: ${sentence}

Facts (JSON): ${JSON.stringify(facts)}

Rewrite the sentence using only numbers present in the facts, or remove the numbers. Reply with the sentence only.`;
}
